import { strict as assert } from 'node:assert';
import { mkdir } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { chromium } from 'file:///C:/Users/Windows-10/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright/index.mjs';

const output = fileURLToPath(new URL('.', import.meta.url));
await mkdir(output,{recursive:true});
const browser = await chromium.launch({headless:true,executablePath:'C:/Program Files/Google/Chrome/Application/chrome.exe',args:['--no-sandbox']});
const context = await browser.newContext({viewport:{width:390,height:844},reducedMotion:'reduce'});
const page = await context.newPage();
const errors=[];
page.on('pageerror',error=>errors.push(error.message));
try {
  await page.goto('http://127.0.0.1:8771/',{waitUntil:'networkidle'});
  await page.getByRole('button',{name:'Создать проект'}).click();
  await page.locator('#project-form-wizard').waitFor({state:'visible'});
  assert.equal(await page.locator('#project-form-wizard').isVisible(),true,'wizard should be visible at phone width');
  assert.equal(await page.locator('#project-form-step-title').innerText(),'Основа проекта');
  assert.equal(await page.locator('[name=context]').isVisible(),false,'story fields should be hidden in step 1');
  await page.screenshot({path:output+'\\step-1-basics.png',fullPage:false});
  await page.getByRole('button',{name:/Далее/}).click();
  assert.equal(await page.locator('#project-dialog').evaluate(el=>el.dataset.mobileStep),'0','required fields must prevent leaving step 1');
  await page.locator('[name=title]').fill('Wizard QA Portfolio Case');
  await page.locator('#project-form [name=description]').fill('Проверка пошаговой мобильной формы создания и редактирования кейса.');
  await page.getByRole('button',{name:/Далее/}).click();
  await page.waitForFunction(()=>document.querySelector('#project-dialog')?.dataset.mobileStep==='1');
  assert.equal(await page.locator('#project-dialog').evaluate(el=>el.dataset.mobileStep),'1');
  assert.equal(await page.locator('.case-guide').isVisible(),true);
  assert.equal(await page.locator('[name=context]').isVisible(),true);
  await page.screenshot({path:output+'\\step-2-story.png',fullPage:false});
  await page.locator('[name=context]').fill('Учебная задача для проверки сохранения значений между шагами.');
  await page.locator('[name=role]').fill('Проектирование и проверка интерфейса');
  await page.getByRole('button',{name:/Назад/}).click();
  assert.equal(await page.locator('[name=context]').inputValue(),'Учебная задача для проверки сохранения значений между шагами.','hidden story values must persist when navigating back');
  assert.equal(await page.locator('[name=title]').inputValue(),'Wizard QA Portfolio Case');
  await page.getByRole('button',{name:/Далее/}).click();
  await page.getByRole('button',{name:/Далее/}).click();
  assert.equal(await page.locator('#project-dialog').evaluate(el=>el.dataset.mobileStep),'2');
  assert.equal(await page.locator('#cover-preview').isVisible(),true);
  await page.screenshot({path:output+'\\step-3-media.png',fullPage:false});
  const overflow=await page.evaluate(()=>({viewport:innerWidth,document:document.documentElement.scrollWidth}));
  assert.ok(overflow.document<=overflow.viewport,`mobile form overflows horizontally: ${JSON.stringify(overflow)}`);
  await page.getByRole('button',{name:/Сохранить проект/}).click();
  await page.locator('#project-dialog').waitFor({state:'hidden'});
  await page.reload({waitUntil:'networkidle'});
  await page.locator('.mobile-nav-item[data-view="projects"]').click();
  assert.equal(await page.getByText('Wizard QA Portfolio Case',{exact:true}).count()>0,true,'created case should survive reload');
  const card=page.locator('button').filter({hasText:'Wizard QA Portfolio Case'}).first();
  await card.click();
  await page.locator('[data-edit]').first().click();
  await page.waitForFunction(()=>document.querySelector('#project-form [name=title]')?.value==='Wizard QA Portfolio Case');
  assert.equal(await page.locator('#project-form-step-title').innerText(),'Основа проекта');
  assert.equal(await page.locator('[name=title]').inputValue(),'Wizard QA Portfolio Case');
  await page.locator('[name=title]').fill('Wizard QA Portfolio Case Edited');
  await page.getByRole('button',{name:/Далее/}).click();
  assert.equal(await page.locator('[name=context]').inputValue(),'Учебная задача для проверки сохранения значений между шагами.');
  await page.getByRole('button',{name:/Далее/}).click();
  await page.getByRole('button',{name:/Сохранить проект/}).click();
  await page.locator('#project-dialog').waitFor({state:'hidden'});
  await page.reload({waitUntil:'networkidle'});
  await page.locator('.mobile-nav-item[data-view="projects"]').click();
  assert.equal(await page.getByText('Wizard QA Portfolio Case Edited',{exact:true}).count()>0,true,'edit should persist through reload');
  assert.deepEqual(errors,[],'browser console should have no uncaught page errors');
  process.stdout.write(JSON.stringify({status:'PASS',viewport:390,formSteps:3,createPersists:true,editPersists:true,storyValuesPreserved:true,horizontalOverflow:overflow,uncaughtPageErrors:errors,screenshots:['step-1-basics.png','step-2-story.png','step-3-media.png']},null,2)+'\\n');
} finally { await context.close(); await browser.close(); }

